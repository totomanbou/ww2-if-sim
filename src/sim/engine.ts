const joinNames = (sim: SimState, cs: number[]) => cs.map((c) => sim.names[c]).join("・");

function log(sim: SimState, type: EventType, countries: number[], text: string, extra: object = {}) {
  sim.events.push({
    tick: sim.tick,
    date: formatDate(tickTime(sim.startMs, sim.tick, sim.config.stepDays)),
    type,
    countries: countries.map((c) => sim.tags[c]),
    text,
    ...extra,
  });
}

function logCapitalChanges(sim: SimState) {
  for (const { country, by, recaptured } of capitalChanges(sim)) {
    const cityName = capitalName(sim.tags[country]);
    log(sim, recaptured ? "capitalRecapture" : "capitalFall", [country, by],
      occupationText(countryNewsName(sim.scenario, sim.tags[by]), cityName, recaptured), { cityName });
  }
}

/** Activates war declarations whose date has been reached. */
function startWars(sim: SimState, nowMs: number) {
  const nC = sim.tags.length;
  const idx = new Map(sim.tags.map((t, i) => [t, i]));
  while (sim.nextWar < sim.wars.length && parseDate(sim.wars[sim.nextWar].date) <= nowMs) {
    const w = sim.wars[sim.nextWar++];
    const alive = (t: string) => idx.has(t) && !sim.capitulated[idx.get(t)!];
    const as = w.a.filter(alive).map((t) => idx.get(t)!);
    const bs = w.b.filter(alive).map((t) => idx.get(t)!);
    if (!as.length || !bs.length) continue;
    for (const c of [...as, ...bs]) sim.entered[c] = 1;
    // Surprise attack on a listed defender (config.surprise), once.
    // Not for wars generated by a faction change (applyFactions): only historical attacks are surprises.
    if (w.note !== FACTION_WAR_NOTE) {
      for (const b of bs) if (sim.config.surprise[sim.tags[b]] && sim.surpriseStart[b] < 0) sim.surpriseStart[b] = sim.tick;
    }
    for (const a of as) for (const b of bs) {
      sim.atWar[a * nC + b] = 1;
      sim.atWar[b * nC + a] = 1;
    }
    log(sim, "war", [...as, ...bs], `${joinNames(sim, as)} と ${joinNames(sim, bs)} が交戦状態に入った`, { split: as.length });
  }
}

/** Grants each configured war-start army/navy reinforcement once, including wars added by faction changes. */
function applyWarStartReinforcements(sim: SimState) {
  const nC = sim.tags.length;
  sim.config.warStartReinforcements.forEach((r, k) => {
    if (sim.warStartDone[k]) return;
    const to = sim.tags.indexOf(r.to);
    if (to < 0 || sim.capitulated[to]) return;
    const atWar = r.against.some((tag) => {
      const against = sim.tags.indexOf(tag);
      return against >= 0 && !!sim.atWar[to * nC + against];
    });
    if (!atWar) return;
    sim.warStartDone[k] = 1;
    sim.military[to] += sim.industry[to] * sim.stability[to] * r.years;
    const fleets = sim.fleets.filter((f) => f.country === to);
    if (fleets.length) {
      const growth = sim.shipbuilding[to] * sim.stability[to] * r.years / fleets.length;
      for (const f of fleets) f.strength += growth;
    }
  });
}

/**
 * Scenario transfers (e.g. French colonies joining Free France): each one due by now whose `from` has capitulated
 * hands over the states `from` still holds of its original territory inside the boxes. A transfer whose date has
 * passed waits until `from` capitulates.
 */
function applyTransfers(sim: SimState, nowMs: number) {
  sim.transfers.forEach((tr, k) => {
    if (sim.transferDone[k] || parseDate(tr.date) > nowMs) return;
    const from = sim.tags.indexOf(tr.from), to = sim.tags.indexOf(tr.to);
    if (from < 0 || to < 0 || !sim.capitulated[from] || sim.capitulated[to]) return;
    sim.transferDone[k] = 1;
    let n = 0;
    for (let s = 0; s < sim.nStates; s++) {
      if (sim.owner[s] !== from || sim.origOwner[s] !== from) continue;
      const lon = sim.stateLonLat[2 * s], lat = sim.stateLonLat[2 * s + 1];
      if (!tr.boxes.some(([w, so, e, no]) => lon >= w && lon <= e && lat >= so && lat <= no)) continue;
      setOwner(sim, s, to);
      n++;
    }
    if (n) log(sim, "transfer", [to, from], tr.text ? `${tr.text}(${n}州)` : `${tr.name}が${sim.names[to]}に合流(${n}州)`);
  });
}

/**
 * Capitals of successor governments (config.successors): the predecessor's capital if the successor holds it,
 * otherwise its state nearest to the seat, -1 while it holds nothing.
 */
function updateSeats(sim: SimState) {
  for (const [pred, { tag, seat }] of Object.entries(sim.config.successors)) {
    const p = sim.tags.indexOf(pred), c = sim.tags.indexOf(tag);
    if (p < 0 || c < 0 || sim.origCount[c] > 0) continue;
    let cap = -1;
    if (sim.owner[sim.capital[p]] === c) cap = sim.capital[p];
    else {
      let best = Infinity;
      const k = Math.cos((seat[1] * Math.PI) / 180);
      for (let s = 0; s < sim.nStates; s++) {
        if (sim.owner[s] !== c) continue;
        const d = ((sim.stateLonLat[2 * s] - seat[0]) * k) ** 2 + (sim.stateLonLat[2 * s + 1] - seat[1]) ** 2;
        if (d < best) { best = d; cap = s; }
      }
    }
    sim.capital[c] = cap;
  }
}

function recordHistory(sim: SimState, eff: Float64Array) {
  const m = { axis: 0, allies: 0 }, n = { axis: 0, allies: 0 }, ind = { axis: 0, allies: 0 };
  const navy = navyTotals(sim);
  for (let c = 0; c < sim.tags.length; c++) {
    const f = sim.faction[c];
    if (f === "neutral" || sim.capitulated[c]) continue;
    m[f] += sim.military[c];
    n[f] += navy[c];
    ind[f] += eff[c];
  }
  sim.history.push({ tick: sim.tick, military: m, navy: n, industry: ind });
}

function finish(sim: SimState, winner: SimResult["winner"], condition: VictoryCondition | null) {
  sim.result = { winner, condition, endTick: sim.tick, endDate: formatDate(tickTime(sim.startMs, sim.tick, sim.config.stepDays)) };
}

/**
 * Advances the simulation by one half-week. Order: wars → growth (army, navy) → fleet movement → fleet
 * battles → land/landing combat → capitulation → capital and city events → victory check → history.
 * Does nothing once a result exists.
 */
// Diagnostics may read the resolved battles before captures are applied (do not mutate them or the simulation).
export function step(sim: SimState, observeCombat?: (battles: ReturnType<typeof resolveCombat>, fronts: ReturnType<typeof computeFrontsCached>) => void) {
  if (sim.result) return;
  const now = tickTime(sim.startMs, sim.tick, sim.config.stepDays);
  if (now > sim.endMs) {
    log(sim, "stalemate", [], "打ち切り日に到達: 膠着");
    finish(sim, "stalemate", null);
    return;
  }
  startWars(sim, now);
  applyWarStartReinforcements(sim);

  const eff = effectiveIndustry(sim);
  applyGrowth(sim, eff, new Date(now).getUTCFullYear(), weekContainsSept1(now, sim.config.stepDays));
  applyNavyGrowth(sim, weekContainsSept1(now, sim.config.stepDays));

  moveFleets(sim);
  for (const b of resolveFleetBattles(sim)) {
    if (Math.min(b.before.axis, b.before.allies) < sim.config.fleetBattleLogMin) continue;
    const r = (x: number) => Math.round(x);
    log(sim, "fleetBattle", [...b.main.axis, ...b.main.allies],
      `${sim.zoneNames[b.zone]}で艦隊決戦(${joinNames(sim, b.main.axis)} 対 ${joinNames(sim, b.main.allies)}): ` +
      `海軍力 枢軸 ${r(b.before.axis)}→${r(b.before.axis - b.loss.axis)}、連合 ${r(b.before.allies)}→${r(b.before.allies - b.loss.allies)}`,
      { zone: b.zone });
  }

  const fronts = computeFrontsCached(sim);
  const battles = resolveCombat(sim, fronts);
  observeCombat?.(battles, fronts);
  for (const r of applyBattles(sim, battles)) {
    log(sim, "revival", [r.country, r.by], `${sim.names[r.country]}が復活(${sim.names[r.by]}が旧領を解放)`);
  }

  logCapitalChanges(sim);
  const returned: Revival[] = [];
  for (const [c, to] of checkCapitulations(sim, returned)) {
    // An ally taking over the remaining territory (config.capitulationOccupier) occupies it; an enemy receives it.
    const occupied = to >= 0 && sim.faction[to] === sim.faction[c];
    log(sim, "capitulation", to >= 0 ? [c, to] : [c],
      to < 0 ? `${sim.names[c]}が降伏`
        : occupied ? `${sim.names[c]}が降伏。残る領土は${sim.names[to]}が占領` : `${sim.names[c]}が降伏。残る領土は${sim.names[to]}へ`,
      occupied ? { occupied: true } : {});
  }
  for (const r of returned) log(sim, "revival", [r.country, r.by], `${sim.names[r.country]}が復活(${sim.names[r.by]}が受け取った旧領を返還)`);
  applyTransfers(sim, now);
  updateSeats(sim);
  // Capitulation can transfer capitals in bulk; an ally or successor may also liberate one this week.
  logCapitalChanges(sim);
  for (const city of ALL_CITIES) {
    const fallen = isFallen(sim, city);
    if (fallen === sim.cityFallen[city]) continue;
    sim.cityFallen[city] = fallen;
    const by = sim.owner[sim.cities[city]];
    log(sim, fallen ? "cityFall" : "cityRecapture", [by],
      occupationText(countryNewsName(sim.scenario, sim.tags[by]), CITY_NAMES[city], !fallen), { city });
  }

  sim.importantCities.forEach((city, i) => {
    const fallen = importantCityFallen(sim, i);
    if (fallen === !!sim.importantCityFallen[i]) return;
    sim.importantCityFallen[i] = fallen ? 1 : 0;
    const by = sim.owner[city.state];
    // Only opposing factions are occupation/liberation. A neutral hand-over is neither.
    const home = sim.tags.indexOf(city.home);
    if (sim.faction[by] === "neutral" || sim.faction[home] === "neutral" || home < 0) return;
    log(sim, fallen ? "cityFall" : "cityRecapture", [by],
      occupationText(countryNewsName(sim.scenario, sim.tags[by]), city.name, !fallen),
      { importantCity: city.id, cityName: city.name });
    // Reinforcements for the first fall of the city (config.cityFallReinforcements).
    if (!fallen) return;
    sim.config.cityFallReinforcements.forEach((r, k) => {
      if (r.city !== city.name || sim.reinforcementsDone[k]) return;
      const to = sim.tags.indexOf(r.to);
      if (to < 0 || sim.capitulated[to]) return;
      sim.reinforcementsDone[k] = 1;
      sim.military[to] += sim.industry[to] * sim.stability[to] * r.years;
    });
  });

  const cond = checkVictory(sim);
  recordHistory(sim, effectiveIndustry(sim));
  if (cond) {
    const winner = cond === "allies" ? "allies" : "axis";
    const label = { axisA: "枢軸国の勝利(条件A)", axisB: "枢軸国の勝利(条件B)", allies: "連合国の勝利" }[cond];
    log(sim, "victory", [], label);
    finish(sim, winner, cond);
    return;
  }
  sim.tick++;
}

/** Runs until a result (victory or stalemate at the cut-off date). */
export function runToEnd(sim: SimState): SimResult {
  while (!sim.result) step(sim);
  return sim.result!;
}
